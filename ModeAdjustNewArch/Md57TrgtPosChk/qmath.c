ptTyp ptSolveLinkMidY(ptTyp A,ptTyp B,qm_float MA,qm_float MB) {
	ptTyp ans1,ans2;
	ptTyp AA,BB;
	qm_float x,y,r,D1,a,b,aa,bb;
	qm_bool isSwap=FALSE;
	//swap x/z according to the distance if needed to improve the accuracy
	if(qabs(A.x,B.x)>qabs(A.z,B.z)) {
		AA.x=A.x;AA.z=A.z;
		BB.x=B.x;BB.z=B.z;
	}
	else {
		AA.x=A.z;AA.z=A.x;
		BB.x=B.z;BB.z=B.x;
		isSwap=TRUE;
	}
	x=AA.x*AA.x;
	y=AA.z*AA.z;
	r=MA*MA;
	D1=-2.0F*AA.x;
	a=(AA.z-BB.z)/(BB.x-AA.x);
	b=((BB.x*BB.x)+(BB.z*BB.z)-(MB*MB)-x-y+r)/(2.0F*(BB.x-AA.x));
	aa=(2.0F*a*a)+2.0F;
	bb=(2.0F*a*b)+(D1*a)-(2.0F*AA.z);
	r=qsqrt((bb*bb)-(2.0F*aa*((b*b)+(D1*b)+x+y-r)));
	ans1.z=(-bb+r)/aa;
	ans1.x=(a*ans1.z)+b;
	ans2.z=(-bb-r)/aa;
	ans2.x=(a*ans2.z)+b;
	if(isSwap) {
		x=ans1.x;
		ans1.x=ans1.z;
		ans1.z=x;
		x=ans2.x;
		ans2.x=ans2.z;
		ans2.z=x;
	}
	AA=ptMinusY(B,A);
	BB=ptMinusY(ans1,A);
	x=AA.x*BB.z-BB.x*AA.z;
	if(x<0) {
		return ans2;
	}
	return ans1;
}

