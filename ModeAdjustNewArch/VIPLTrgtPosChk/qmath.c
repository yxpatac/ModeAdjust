ptTyp ptSolveLinkMidY(ptTyp A,ptTyp B,float MA,float MB) {
	float x=A.x*A.x;
	float y=A.z*A.z;
	float r=MA*MA;
	float D1=-2*A.x;
	float a=(A.z-B.z)/(B.x-A.x);
	float b=(B.x*B.x+B.z*B.z-MB*MB-x-y+r)/(2*(B.x-A.x));
	float aa=a*a+1;
	float bb=2*a*b+D1*a-2*A.z;
	r=qsqrt(bb*bb-4*aa*(b*b+D1*b+x+y-r));
	ptTyp ans;
	ans.z=(-bb+r)/(2*aa);//y2=(-bb-r)/(2*aa);
	ans.x=a*ans.z+b;//x2=a*y2+b;
	return ans;
}

float ptDistY(ptTyp a,ptTyp b) {
	float abx=a.x-b.x;
	float abz=a.z-b.z;
	return qsqrt(abx*abx+abz*abz);
}

ptTyp ptRotY(ptTyp p, float r) {
	ptTyp ans;
	ans.x=qcos(r)*p.x+qsin(r)*p.z;
	ans.z=-qsin(r)*p.x+qcos(r)*p.z;
	return ans;
}

ptTyp ptUnitY(ptTyp A,ptTyp B) {
	float m=ptDistY(A,B);
	ptTyp ans=ptMinusY(B,A);
	ans.x=ans.x/m;
	ans.z=ans.z/m;
	return ans;
}

float ptAbsY(ptTyp A) {
	return qsqrt(A.x*A.x+A.z*A.z);
}

float ptAngleIncY(ptTyp A,ptTyp B) {
	return qacos((A.x*B.x+A.z*B.z)/(ptAbsY(A)*ptAbsY(B)));
}

ptTyp ptGetPedalY(ptTyp D,ptTyp A,ptTyp B) {
    float dx=A.x-B.x;
    float dz=A.z-B.z;
    float u=(D.x-A.x)*dx+(D.z-A.z)*dz;
    u=u/(dx*dx+dz*dz);
	ptTyp ans;
	ans.x=A.x+u*dx;
	ans.z=A.z+u*dz;
	return ans;
}

qm_bool ptPedalInSegY(ptTyp P,ptTyp A,ptTyp B) {
    if(((A.x<=B.x && P.x>=A.x && P.x<=B.x)||(B.x<=A.x && P.x>=B.x && P.x<=A.x))
    && ((A.x<=B.x && P.x>=A.x && P.x<=B.x)||(B.x<=A.x && P.x>=B.x && P.x<=A.x))) {
        return TRUE;
	}
	return FALSE;
}

float ptDist2SegY(ptTyp D,ptTyp A,ptTyp B, qm_bool ext) {
    float r;
    ptTyp pd=ptGetPedalY(D,A,B);
	qm_bool in=ptPedalInSegY(pd,A,B);
    float da=ptDistY(pd,A);
    float db=ptDistY(pd,B);
    if(in>0 || ext) {
        r=ptDistY(pd,D);
        if(pd.x>D.x
		|| (pd.z>D.z && A.x>B.x && A.z>B.z)
		|| (pd.z<D.z && A.x<B.x && A.z>B.z)) {
            r=-r;
		}
	}
    else if(da<db) {
		r=ptDistY(A,D);
	}
	else {
		r=ptDistY(B,D);
	}
	return r;
}
